import type { CollectionConfig } from 'payload'

import { isStaff } from '@/access/roles'
import { validateHref } from '@/lib/href'

export const Media: CollectionConfig = {
  slug: 'media',
  admin: { group: 'Content' },
  access: {
    read: () => true,
    create: isStaff,
    update: isStaff,
    delete: isStaff,
  },
  upload: {
    mimeTypes: ['image/*', 'video/webm', 'video/mp4'],
    imageSizes: [
      { name: 'card', width: 640 },
      { name: 'feature', width: 1280 },
    ],
  },
  hooks: {
    afterRead: [({ doc }) => {
      const publicBase = process.env.S3_PUBLIC_URL?.replace(/\/$/, '')
      if (!publicBase) return doc
      const publicPath = (filename?: string | null) => filename ? `${publicBase}/${filename}` : null
      const sizes = Object.fromEntries(Object.entries(doc.sizes ?? {}).map(([name, size]) => {
        if (!size || typeof size !== 'object') return [name, size]
        const sizeRecord = size as Record<string, unknown>
        const filename = typeof sizeRecord.filename === 'string' ? sizeRecord.filename : null
        return [name, { ...sizeRecord, url: publicPath(filename) }]
      }))
      return {
        ...doc,
        url: publicPath(doc.filename),
        sizes: doc.sizes ? sizes : doc.sizes,
      }
    }],
  },
  fields: [
    { name: 'alt', type: 'text', required: true },
    {
      name: 'license',
      type: 'select',
      required: true,
      defaultValue: 'own',
      options: [
        { label: 'Own / generated by us', value: 'own' },
        { label: 'Public domain', value: 'public-domain' },
        { label: 'CC0', value: 'cc0' },
        { label: 'CC BY', value: 'cc-by' },
        { label: 'CC BY-SA', value: 'cc-by-sa' },
        { label: 'Other (explain in credit)', value: 'other' },
      ],
      admin: { description: 'Har asset ka license zaroori hai (ASSETS.md policy).' },
    },
    { name: 'credit', type: 'text', admin: { description: 'Author / attribution text' } },
    { name: 'sourceUrl', type: 'text', validate: validateHref },
  ],
}
