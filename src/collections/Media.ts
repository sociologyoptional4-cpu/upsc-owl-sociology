import { APIError, type CollectionBeforeValidateHook, type CollectionConfig } from 'payload'

import { isStaff } from '@/access/roles'
import { validateHref } from '@/lib/href'
import { deriveAlt, uploadSizeError } from '@/lib/mediaRules'
import { resolveStaticMediaUrl } from '@/lib/notes/static-media'

/** Paste/upload without a form: fill alt from the filename and enforce size limits (docs/09 C1). */
const prepareUpload: CollectionBeforeValidateHook = ({ data, req, operation }) => {
  if (operation !== 'create' || !req.file) return data
  const tooBig = uploadSizeError(req.file.mimetype, req.file.size)
  if (tooBig) throw new APIError(tooBig, 400, undefined, true)
  return data?.alt ? data : { ...data, alt: deriveAlt(req.file.name) }
}

export const Media: CollectionConfig = {
  slug: 'media',
  admin: { group: 'Content' },
  access: {
    read: () => true,
    create: isStaff,
    update: isStaff,
    delete: isStaff,
  },
  upload: {
    mimeTypes: ['image/*', 'video/webm', 'video/mp4', 'application/pdf'],
    resizeOptions: { width: 2000, withoutEnlargement: true },
    imageSizes: [
      { name: 'card', width: 640 },
      { name: 'feature', width: 1280 },
    ],
  },
  hooks: {
    beforeValidate: [prepareUpload],
    afterRead: [({ doc }) => {
      const staticUrl = resolveStaticMediaUrl(doc.filename)
      if (staticUrl) {
        const staticSizes = Object.fromEntries(Object.entries(doc.sizes ?? {}).map(([name, size]) => [name, size && typeof size === 'object' ? { ...size, url: staticUrl } : size]))
        return { ...doc, url: staticUrl, sizes: doc.sizes ? staticSizes : doc.sizes }
      }
      const publicBase = process.env.S3_PUBLIC_URL?.replace(/\/$/, '')
      if (!publicBase) return doc
      const publicPath = (filename?: string | null) => filename ? `${publicBase}/${filename}` : null
      const sizes = Object.fromEntries(Object.entries(doc.sizes ?? {}).map(([name, size]) => {
        if (!size || typeof size !== 'object') return [name, size]
        const sizeRecord = size as Record<string, unknown>
        const filename = typeof sizeRecord.filename === 'string' ? sizeRecord.filename : null
        return [name, { ...sizeRecord, url: publicPath(filename) }]
      }))
      return {
        ...doc,
        url: publicPath(doc.filename),
        sizes: doc.sizes ? sizes : doc.sizes,
      }
    }],
  },
  fields: [
    // Match the cloud-storage field even when the S3 plugin is disabled locally.
    { name: '_objectKey', type: 'text', admin: { hidden: true, readOnly: true } },
    { name: 'alt', type: 'text', required: true, admin: { description: 'Khaali chhodo to file ke naam se bharega. SEO ke liye behtar likho.' } },
    {
      name: 'license',
      type: 'select',
      required: true,
      defaultValue: 'own',
      options: [
        { label: 'Own / generated by us', value: 'own' },
        { label: 'Public domain', value: 'public-domain' },
        { label: 'CC0', value: 'cc0' },
        { label: 'CC BY', value: 'cc-by' },
        { label: 'CC BY-SA', value: 'cc-by-sa' },
        { label: 'Other (explain in credit)', value: 'other' },
      ],
      admin: { description: 'Har asset ka license zaroori hai (ASSETS.md policy). PDF public hoti hai, private handout mat daalo (D15).' },
    },
    { name: 'credit', type: 'text', admin: { description: 'Author / attribution text' } },
    { name: 'sourceUrl', type: 'text', validate: validateHref },
  ],
}
